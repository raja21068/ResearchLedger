"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import { api } from "@/lib/api";
import type { WorkspaceFile } from "@/lib/types";
import { useProject } from "@/lib/useProject";
import { btn2, Card, Empty, ErrorBox, PageHeader } from "@/components/ui";

interface Results { files: WorkspaceFile[]; measured: unknown }

const FOLDERS: [string, string][] = [
  ["4_code/", "Paper Factory experiment (S4) — measured in the Docker sandbox"],
  ["results/", "Results written by your code and analysis scripts"],
  ["analysis/", "Analysis plans and scripts"],
  ["5_refine/", "Evidence-bound revision (S5)"],
  ["code/outputs/", "Code outputs"],
];

export default function ResultsPage() {
  const { projects, projectId, setProjectId, error: loadError } = useProject();
  const [res, setRes] = useState<Results | null>(null);
  const [error, setError] = useState<unknown>(null);

  useEffect(() => {
    if (projectId) api<Results>(`/projects/${projectId}/results`).then(setRes).catch(setError);
  }, [projectId]);

  return (
    <main className="mx-auto max-w-[1180px] px-4 py-7 sm:px-8">
      <PageHeader title="Results"
        sub="Measured results and result files in the project. Only files that exist are shown; nothing here is generated by a model without running code."
        actions={projectId && <Link className={btn2} href={`/tools/code_generation?project=${projectId}`}>Code generation</Link>} />
      <ErrorBox error={loadError || error} />
      {projects && !projects.length && <Empty title="No projects yet"><Link className="text-accent underline" href="/projects?new=1">Create a project</Link></Empty>}
      {projects && projects.length > 0 && (
        <select aria-label="Project" value={projectId} onChange={(e) => setProjectId(e.target.value)}
          className="mb-4 min-h-10 rounded-lg border border-line bg-white px-2 text-sm">
          {projects.map((p) => <option key={p.id} value={p.id}>{p.title}</option>)}
        </select>
      )}

      {res && res.measured != null && (
        <Card className="mb-4 p-5">
          <h2 className="font-semibold">Measured results (4_code/results.json)</h2>
          <pre className="mt-2 max-h-96 overflow-auto rounded-lg bg-[#f6f8fa] p-3 font-mono text-xs">{JSON.stringify(res.measured, null, 2)}</pre>
        </Card>
      )}
      {res && !res.files.length && (
        <Empty title="No results yet">
          Generate code with <Link className="text-accent underline" href={`/tools/code_generation?project=${projectId}`}>Code generation</Link> or{" "}
          <Link className="text-accent underline" href={`/tools/data_analysis?project=${projectId}`}>Data analysis</Link>, then run it with{" "}
          <Link className="text-accent underline" href={`/tools/experiments_s4?project=${projectId}`}>Run experiments (S4)</Link>.
        </Empty>
      )}
      <div className="grid gap-4">
        {FOLDERS.map(([prefix, label]) => {
          const items = res?.files.filter((f) => f.path.startsWith(prefix)) ?? [];
          if (!items.length) return null;
          return (
            <Card key={prefix} className="p-5">
              <h2 className="font-semibold">{label} <span className="text-faint">({items.length})</span></h2>
              <ul className="mt-2 divide-y divide-[#e6eaee]">
                {items.map((f) => (
                  <li key={f.path} className="flex flex-wrap items-center justify-between gap-2 py-2 text-sm">
                    <Link href={`/view/${projectId}?path=${encodeURIComponent(f.path)}`} target="_blank" className="font-mono text-accent">{f.path}</Link>
                    <span className="text-xs text-faint">{(f.size / 1024).toFixed(1)} KB · {new Date(f.modified * 1000).toLocaleString()}</span>
                  </li>
                ))}
              </ul>
            </Card>
          );
        })}
      </div>
    </main>
  );
}
